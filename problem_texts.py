def enrich_bank(bank):
    import ast
    for p in bank:
        p["solution"]=ast.unparse(ast.parse(p["solution"]))
        if p['id'] in TEXTS:
            statement,layout,inp,constraints,out,samples,explanation=TEXTS[p['id']]
            p.update(statement=statement,input_format=layout,input=inp,constraints=constraints,
                     output=out,sample_explanation=explanation)
            p['cases']=samples+[case for case in p['cases'] if case not in samples]
        p['output_format']=('#tc root_value node_value' if p['id'] in ('FA-L3','FB-L3') else '#tc value2 value3 ... valueN' if p['id'] in ('FA-L4','FB-L4') else '#tc answer')
    return bank
